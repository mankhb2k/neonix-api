async function main() {
  const pricing = renderPricingFromEnv();
  const project = await db.query.projects.findFirst({ where: eq(projects.id, DEMO_PROJECT_ID) });
  let inserted = 0;
  for (const run of RUNS) {
    const startedAt = new Date(run.startedAt);
    const completedAt = new Date(run.completedAt);
    const billedMs = completedAt.getTime() - startedAt.getTime();
    const cost = computeRenderRunCost({ vcpu: run.vcpu, memoryGib: 16, billedMs, outputBytes: run.outputBytes }, pricing);
    const result = await db
      .insert(renderRuns)
      .values({
        runKind: "benchmark",
        status: "succeeded",
        workspaceId: project?.workspaceId ?? null,
        projectId: project?.id ?? null,
        executionName: run.executionName,
        imageDigest: run.imageDigest,
        vcpu: run.vcpu,
        memoryGib: 16,
        workers: run.workers,
        width: run.width,
        height: run.height,
        fps: run.fps,
        videoMs: run.videoMs,
        outputBytes: run.outputBytes,
        createdAtRun: new Date(run.createdAt),
        startedAt,
        completedAt,
        billedMs,
        captureMs: Math.round(run.captureSeconds * 1000),
        peakMemoryBytes: run.peakMemoryBytes,
        vcpuSecondUsd: String(pricing.vcpuSecondUsd),
        gibSecondUsd: String(pricing.gibSecondUsd),
        egressUsdPerGib: String(pricing.egressUsdPerGib),
        usdVndRate: String(pricing.usdVndRate),
        ...cost,
        priceVnd: 0,
        metadata: { benchmarkId: run.benchmarkId, content: run.content, label: run.label, wallSeconds: run.wallSeconds, inJobSeconds: run.inJobSeconds },
      })
      .onConflictDoNothing({ target: renderRuns.executionName })
      .returning({ id: renderRuns.id });
    if (result.length > 0) inserted += 1;
  }
  console.log(`[import] inserted ${inserted} of ${RUNS.length} benchmark runs`);

  const summary = await db.execute(sql`
    select width || 'x' || height || '@' || fps as format, vcpu, (video_ms / 1000) as video_s, metadata->>'content' as content, count(*) as runs,
           round(avg(billed_ms) / 1000.0, 1) as avg_billed_s, round(avg(cost_vnd)) as avg_cost_vnd, max(cost_vnd) as worst_cost_vnd
    from render_runs where run_kind = 'benchmark' group by 1, 2, 3, 4 order by 2, 1, 3`);
  console.table(summary.rows);
  await pool.end();
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
